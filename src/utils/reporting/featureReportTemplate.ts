const SCRIPT = `
(() => {
  const hidden = new Set();

  const apply = () => {
    document.querySelectorAll('.scenario').forEach((row) => {
      row.style.display = hidden.has(row.dataset.bucket) ? 'none' : '';
    });
    document.querySelectorAll('.feature').forEach((feature) => {
      const buckets = (feature.dataset.buckets || '').split(' ').filter(Boolean);
      const visible = buckets.some((bucket) => !hidden.has(bucket));
      feature.style.display = visible ? '' : 'none';
    });
  };

  document.querySelectorAll('.chip[data-filter]').forEach((chip) => {
    chip.addEventListener('click', () => {
      const bucket = chip.dataset.filter;
      const on = chip.getAttribute('aria-pressed') === 'true';
      chip.setAttribute('aria-pressed', String(!on));
      if (on) hidden.add(bucket); else hidden.delete(bucket);
      apply();
    });
  });

  const setAll = (open) => document.querySelectorAll('details').forEach((d) => { d.open = open; });
  document.getElementById('expand-all').addEventListener('click', () => setAll(true));
  document.getElementById('collapse-all').addEventListener('click', () => setAll(false));

  // Failures are the reason anyone opens this, so surface them without a click.
  document.querySelectorAll('.feature').forEach((feature) => {
    const buckets = (feature.dataset.buckets || '').split(' ');
    if (buckets.includes('failed') || buckets.includes('broken')) {
      feature.open = true;
      feature.querySelectorAll('.scenario[data-bucket="failed"], .scenario[data-bucket="broken"]')
        .forEach((row) => { row.open = true; });
    }
  });
})();
`;
