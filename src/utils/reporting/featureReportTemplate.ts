/**
 * Markup for the feature-oriented HTML report. Kept apart from the reporter so
 * the look of the report can be changed without touching result collection.
 */

export const BUCKETS = ['passed', 'failed', 'broken', 'skipped', 'other'] as const;

export type Bucket = (typeof BUCKETS)[number];

export type Totals = Record<Bucket, number>;

export type StepReport = {
  title: string;
  durationMs: number;
  failed: boolean;
};

export type AttachmentReport = {
  name: string;
  /** Report-relative link, absent for attachments held in memory. */
  href?: string;
  /** Original location on disk, carried through to the JSON summary. */
  path?: string;
  isImage: boolean;
};

export type ScenarioReport = {
  name: string;
  project: string;
  location: string;
  bucket: Bucket;
  flaky: boolean;
  durationMs: number;
  retries: number;
  tags: string[];
  steps: StepReport[];
  annotations: { type: string; description?: string }[];
  error?: string;
  attachments: AttachmentReport[];
  /** Web vitals lifted out of the attachment, when the scenario captured them. */
  performance?: Record<string, number>;
};

export type FeatureReport = {
  name: string;
  path: string;
  totals: Totals;
  durationMs: number;
  scenarios: ScenarioReport[];
};

export type RunReport = {
  status: string;
  startedAt: string;
  durationMs: number;
  totals: Totals;
  flaky: number;
  features: FeatureReport[];
};

const BUCKET_LABELS: Record<Bucket, string> = {
  passed: 'Passed',
  failed: 'Failed',
  broken: 'Broken',
  skipped: 'Skipped',
  other: 'Other',
};

export function renderFeatureReport(run: RunReport): string {
  const total = sum(run.totals);
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Feature report — BrainPOP</title>
<style>${STYLES}</style>
</head>
<body>
<header>
  <div class="title">
    <h1>Feature report</h1>
    <span class="run-status ${run.status === 'passed' ? 'ok' : 'bad'}">${esc(run.status)}</span>
  </div>
  <p class="meta">${total} test${total === 1 ? '' : 's'} across ${run.features.length} feature file${
    run.features.length === 1 ? '' : 's'
  } · ${formatDuration(run.durationMs)} · ${esc(run.startedAt)}</p>
</header>

<section class="totals">
  ${BUCKETS.map((bucket) => card(bucket, run.totals[bucket], total)).join('')}
  ${run.flaky > 0 ? `<div class="card flaky"><span class="count">${run.flaky}</span><span class="label">Flaky</span></div>` : ''}
</section>

${bar(run.totals)}

<section class="controls">
  <span class="controls-label">Show</span>
  ${BUCKETS.map(
    (bucket) =>
      `<button class="chip ${bucket}" data-filter="${bucket}" aria-pressed="true">${BUCKET_LABELS[bucket]}</button>`,
  ).join('')}
  <button class="chip plain" id="expand-all">Expand all</button>
  <button class="chip plain" id="collapse-all">Collapse all</button>
</section>

<main>
${run.features.map(feature).join('\n')}
</main>

<footer>
  <p>Generated by <code>featureReporter</code>, which also writes <code>summary.json</code>.
  Traces, videos, and step timelines live in the
  Playwright HTML report (<code>npx playwright show-report</code>).</p>
</footer>

<script>${SCRIPT}</script>
</body>
</html>
`;
}

function card(bucket: Bucket, count: number, total: number): string {
  const pct = total === 0 ? 0 : Math.round((count / total) * 100);
  return `<div class="card ${bucket}">
    <span class="count">${count}</span>
    <span class="label">${BUCKET_LABELS[bucket]}</span>
    <span class="pct">${pct}%</span>
  </div>`;
}

function bar(totals: Totals): string {
  const total = sum(totals);
  if (total === 0) {
    return '';
  }
  const segments = BUCKETS.filter((bucket) => totals[bucket] > 0)
    .map(
      (bucket) =>
        `<span class="seg ${bucket}" style="width:${(totals[bucket] / total) * 100}%" title="${
          BUCKET_LABELS[bucket]
        }: ${totals[bucket]}"></span>`,
    )
    .join('');
  return `<div class="bar">${segments}</div>`;
}

function feature(item: FeatureReport): string {
  const total = sum(item.totals);
  const worst = worstBucket(item.totals);
  return `<details class="feature" data-buckets="${bucketsPresent(item.totals).join(' ')}">
  <summary>
    <span class="dot ${worst}"></span>
    <span class="feature-name">${esc(item.name)}</span>
    <span class="feature-path">${esc(item.path)}</span>
    <span class="counts">${BUCKETS.filter((bucket) => item.totals[bucket] > 0)
      .map((bucket) => `<span class="pill ${bucket}">${item.totals[bucket]} ${BUCKET_LABELS[bucket].toLowerCase()}</span>`)
      .join('')}</span>
    <span class="feature-duration">${formatDuration(item.durationMs)}</span>
  </summary>
  <div class="feature-body">
    ${bar(item.totals)}
    <p class="feature-meta">${total} scenario run${total === 1 ? '' : 's'} including every project</p>
    ${item.scenarios.map(scenario).join('\n')}
  </div>
</details>`;
}

function scenario(item: ScenarioReport): string {
  const hasDetail =
    item.error !== undefined ||
    item.steps.length > 0 ||
    item.attachments.length > 0 ||
    item.annotations.length > 0;

  const head = `<span class="dot ${item.bucket}"></span>
    <span class="scenario-name">${esc(item.name)}</span>
    ${item.flaky ? '<span class="pill flaky">flaky</span>' : ''}
    ${item.retries > 0 ? `<span class="pill retry">${item.retries} retr${item.retries === 1 ? 'y' : 'ies'}</span>` : ''}
    <span class="pill project">${esc(item.project)}</span>
    ${item.tags.map((tag) => `<span class="pill tag">${esc(tag)}</span>`).join('')}
    <span class="scenario-duration">${formatDuration(item.durationMs)}</span>`;

  if (!hasDetail) {
    return `<div class="scenario static" data-bucket="${item.bucket}">${head}</div>`;
  }

  return `<details class="scenario" data-bucket="${item.bucket}">
  <summary>${head}</summary>
  <div class="scenario-body">
    ${item.steps.length > 0 ? steps(item.steps) : ''}
    ${item.error ? `<pre class="error">${esc(item.error)}</pre>` : ''}
    ${item.annotations.length > 0 ? annotations(item.annotations) : ''}
    ${item.attachments.length > 0 ? attachments(item.attachments) : ''}
  </div>
</details>`;
}

function steps(list: StepReport[]): string {
  return `<ol class="steps">${list
    .map(
      (step) =>
        `<li class="${step.failed ? 'failed' : ''}"><span>${esc(step.title)}</span><span class="step-duration">${formatDuration(
          step.durationMs,
        )}</span></li>`,
    )
    .join('')}</ol>`;
}

function annotations(list: { type: string; description?: string }[]): string {
  return `<div class="annotations">${list
    .map(
      (item) =>
        `<span class="annotation"><b>${esc(item.type)}</b>${
          item.description ? ` ${esc(item.description)}` : ''
        }</span>`,
    )
    .join('')}</div>`;
}

function attachments(list: AttachmentReport[]): string {
  const images = list.filter((item) => item.isImage && item.href);
  const files = list.filter((item) => !images.includes(item));

  const gallery =
    images.length > 0
      ? `<div class="attachments">${images
          .map(
            (item) =>
              `<figure><img loading="lazy" src="${esc(item.href ?? '')}" alt="${esc(
                item.name,
              )}"><figcaption>${esc(item.name)}</figcaption></figure>`,
          )
          .join('')}</div>`
      : '';

  const links =
    files.length > 0
      ? `<div class="attachment-links">${files
          .map((item) =>
            item.href
              ? `<a class="attachment" href="${esc(item.href)}">${esc(item.name)}</a>`
              : `<span class="attachment">${esc(item.name)}</span>`,
          )
          .join('')}</div>`
      : '';

  return gallery + links;
}

function bucketsPresent(totals: Totals): Bucket[] {
  return BUCKETS.filter((bucket) => totals[bucket] > 0);
}

function worstBucket(totals: Totals): Bucket {
  const severity: Bucket[] = ['failed', 'broken', 'other', 'skipped', 'passed'];
  return severity.find((bucket) => totals[bucket] > 0) ?? 'passed';
}

function sum(totals: Totals): number {
  return BUCKETS.reduce((acc, bucket) => acc + totals[bucket], 0);
}

export function formatDuration(ms: number): string {
  if (ms < 1000) {
    return `${Math.round(ms)}ms`;
  }
  const seconds = ms / 1000;
  if (seconds < 60) {
    return `${seconds.toFixed(1)}s`;
  }
  const minutes = Math.floor(seconds / 60);
  return `${minutes}m ${Math.round(seconds % 60)}s`;
}

function esc(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

